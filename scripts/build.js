#!/usr/bin/env node
/**
 * Builds the app from web/ in two forms:
 *   src/App.html   the Google page version (pushed to Apps Script with clasp)
 *   dist/          the installable app (published to Firebase Hosting)
 * Settings for the installable app come from app.config.json.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const web = f => fs.readFileSync(path.join(root, 'web', f), 'utf8');

const index = web('index.html');
const shell = index.split('<!--SHELL-->')[1].split('<!--/SHELL-->')[0].trim();
const css = web('app.css');
const app = web('app.js');
const music = web('music.js');
const portraits = web('portraits.js');
const djset = web('djset.js');
const avatar3d = web('avatar3d.js');

// ---- Google page ----
// (No word list here to keep the page light: the server checks guesses.)
for (const [name, src] of [['app.css', css], ['music.js', music], ['portraits.js', portraits], ['djset.js', djset], ['avatar3d.js', avatar3d], ['app.js', app]]) {
  if (src.includes('<?') || src.includes('</script') || src.includes('</style')) throw new Error(name + ' contains text that would break the Google page template');
}
const gas = `<!DOCTYPE html>
<html lang="en-GB" data-theme="<?= theme ?>">
<head>
<base target="_top">
<meta charset="utf-8">
<!-- Generated by scripts/build.js from web/. Edit the files in web/, then run npm run build. -->
<style>
${css}
</style>
</head>
<body>
${shell}
<script>
window.LQ_KEY = <?!= JSON.stringify(key) ?>;
window.LQ_BOOT = <?!= initialJson ?>;
window.LQ_TAB = <?!= JSON.stringify(tab) ?>;
</script>
<script>
${music}
</script>
<script>
${portraits}
</script>
<script>
${djset}
</script>
<script>
${avatar3d}
</script>
<script>
${app}
</script>
</body>
</html>
`;
fs.writeFileSync(path.join(root, 'src', 'App.html'), gas);

// ---- installable app ----
const cfgPath = path.join(root, 'app.config.json');
const cfg = fs.existsSync(cfgPath) ? JSON.parse(fs.readFileSync(cfgPath, 'utf8')) : {};
const dist = path.join(root, 'dist');
fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(dist);
for (const f of fs.readdirSync(path.join(root, 'web'))) {
  if (f === 'config.js') continue;
  fs.copyFileSync(path.join(root, 'web', f), path.join(dist, f));
}
fs.writeFileSync(path.join(dist, 'config.js'), '/* Generated by scripts/build.js from app.config.json. */\nself.LQ_CONFIG = ' + JSON.stringify(cfg, null, 2) + ';\n');
// New cache name each build so phones pick up the update.
const sw = fs.readFileSync(path.join(dist, 'sw.js'), 'utf8').replace("var CACHE = 'lq-v1';", "var CACHE = 'lq-" + Date.now().toString(36) + "';");
fs.writeFileSync(path.join(dist, 'sw.js'), sw);
console.log('Built src/App.html (' + Math.round(gas.length / 1024) + ' KB) and dist/ (' + (cfg.api ? 'api set' : 'no api in app.config.json yet') + ')');

// ---- Chrome add-on (dist/life-quest-chrome.zip) ----
const zlib = require('zlib');
const crcTable = Array.from({ length: 256 }, (_, n) => { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; return c >>> 0; });
const crc32 = buf => { let c = 0xffffffff; for (const b of buf) c = crcTable[(c ^ b) & 0xff] ^ (c >>> 8); return (c ^ 0xffffffff) >>> 0; };
function zip(files) {   // [{name, data}] → Buffer (deflated, no dependencies)
  const parts = [], central = []; let off = 0;
  for (const f of files) {
    const name = Buffer.from(f.name), raw = f.data, def = zlib.deflateRawSync(raw), crc = crc32(raw);
    const local = Buffer.alloc(30); local.writeUInt32LE(0x04034b50, 0); local.writeUInt16LE(20, 4); local.writeUInt16LE(0, 6); local.writeUInt16LE(8, 8);
    local.writeUInt16LE(0, 10); local.writeUInt16LE(0x21, 12); local.writeUInt32LE(crc, 14); local.writeUInt32LE(def.length, 18); local.writeUInt32LE(raw.length, 22);
    local.writeUInt16LE(name.length, 26); local.writeUInt16LE(0, 28);
    const cen = Buffer.alloc(46); cen.writeUInt32LE(0x02014b50, 0); cen.writeUInt16LE(20, 4); cen.writeUInt16LE(20, 6); cen.writeUInt16LE(0, 8); cen.writeUInt16LE(8, 10);
    cen.writeUInt16LE(0, 12); cen.writeUInt16LE(0x21, 14); cen.writeUInt32LE(crc, 16); cen.writeUInt32LE(def.length, 20); cen.writeUInt32LE(raw.length, 24);
    cen.writeUInt16LE(name.length, 28); cen.writeUInt32LE(off, 42);
    parts.push(local, name, def); central.push(cen, name); off += 30 + name.length + def.length;
  }
  const cd = Buffer.concat(central), end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(files.length, 8); end.writeUInt16LE(files.length, 10); end.writeUInt32LE(cd.length, 12); end.writeUInt32LE(off, 16);
  return Buffer.concat([...parts, cd, end]);
}
const extDir = path.join(root, 'extension');
const extCfg = { api: cfg.api || '', app: cfg.appUrl || 'https://' + ((cfg.firebase && cfg.firebase.projectId) || 'life-quest') + '.web.app/' };
const extFiles = fs.readdirSync(extDir).filter(f => f !== 'config.js').sort().map(f => ({ name: 'life-quest/' + f, data: fs.readFileSync(path.join(extDir, f)) }));
extFiles.push({ name: 'life-quest/config.js', data: Buffer.from('/* Generated by scripts/build.js. */\nself.LQ_EXT = ' + JSON.stringify(extCfg) + ';\n') });
fs.writeFileSync(path.join(dist, 'life-quest-chrome.zip'), zip(extFiles));
console.log('Built dist/life-quest-chrome.zip (' + extFiles.length + ' files)');
